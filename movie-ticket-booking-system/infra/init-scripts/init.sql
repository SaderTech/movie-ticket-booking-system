-- 2.4. TẠO BẢNG MOVIES
-- ============================================================

CREATE TABLE public.movies
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    age_rating       VARCHAR(20) NOT NULL,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE,
    description      TEXT,
    duration_minutes INTEGER NOT NULL,
    poster_url       VARCHAR(500),
    release_date     DATE NOT NULL,
    status           VARCHAR(30) NOT NULL,
    title            VARCHAR(255) NOT NULL,
    trailer_url      VARCHAR(500) NOT NULL,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT movies_pkey
        PRIMARY KEY (id),

    CONSTRAINT uk_movie_title_release_date
        UNIQUE (title, release_date),

    CONSTRAINT movies_age_rating_check
        CHECK (
            age_rating IN (
                           'P',
                           'C13',
                           'C16',
                           'C18'
                )
            ),

    CONSTRAINT movies_status_check
        CHECK (
            status IN (
                       'COMING_SOON',
                       'NOW_SHOWING',
                       'ENDED'
                )
            ),

    CONSTRAINT movies_duration_check
        CHECK (duration_minutes > 0)
);


