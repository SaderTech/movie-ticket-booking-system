    price           NUMERIC(19, 2) NOT NULL,
    available_seats INTEGER NOT NULL,
    status          VARCHAR(20) NOT NULL,

    CONSTRAINT chk_showtimes_status
        CHECK (status IN ('AVAILABLE', 'FULL', 'CANCELLED')),
    CONSTRAINT chk_showtimes_available_seats
        CHECK (available_seats >= 0),
    CONSTRAINT chk_showtimes_time_range
        CHECK (end_time > start_time),
    CONSTRAINT uq_showtimes_room_date_start
        UNIQUE (room_id, show_date, start_time)
);

