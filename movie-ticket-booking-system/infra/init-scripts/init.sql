CREATE TABLE public.users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255),
    email         VARCHAR(255),
    password      VARCHAR(255),
    full_name     VARCHAR(255),
    phone         VARCHAR(255),
    avatar        VARCHAR(255),
    date_of_birth DATE,
    gender        VARCHAR(255),
    is_active     BOOLEAN,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE TABLE public.roles
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name   VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE public.user_roles
(
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES public.users (id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES public.roles (id)
);

CREATE TABLE public.refresh_tokens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(500) NOT NULL UNIQUE,
    user_id     BIGINT NOT NULL,
    expiry_date TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    revoked     BOOLEAN,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE
);

CREATE INDEX idx_users_email ON public.users (email);
CREATE INDEX idx_users_username ON public.users (username);
CREATE INDEX idx_refresh_tokens_user_id ON public.refresh_tokens (user_id);


