-- ============================================================
-- 3.1. TẠO BẢNG CINEMAS
-- ============================================================

CREATE TABLE public.cinemas
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    address       TEXT,
    city          VARCHAR(100),
    contact_phone VARCHAR(50),
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    latitude      NUMERIC(10,7),
    longitude     NUMERIC(10,7),
    name          VARCHAR(255) NOT NULL,
    status        VARCHAR(30) NOT NULL,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT cinemas_pkey
        PRIMARY KEY (id),

    CONSTRAINT cinemas_status_check
        CHECK (
            status IN (
                       'ACTIVE',
                       'INACTIVE'
                )
            )
);


-- ============================================================
-- 3.2. TẠO BẢNG SEAT_TYPES
-- ============================================================

CREATE TABLE public.seat_types
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(50) NOT NULL,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    description TEXT,
    name        VARCHAR(100) NOT NULL,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT seat_types_pkey
        PRIMARY KEY (id),

    CONSTRAINT uk_seat_types_code
        UNIQUE (code)
);


-- ============================================================
-- 3.3. TẠO BẢNG HALLS
-- ============================================================

CREATE TABLE public.halls
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    capacity   INTEGER NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    hall_type  VARCHAR(30) NOT NULL,
    name       VARCHAR(255) NOT NULL,
    status     VARCHAR(30) NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    cinema_id  BIGINT NOT NULL,

    CONSTRAINT halls_pkey
        PRIMARY KEY (id),

    CONSTRAINT uk_hall_cinema_name
        UNIQUE (cinema_id, name),

    CONSTRAINT halls_hall_type_check
        CHECK (
            hall_type IN (
                          'STANDARD',
                          'VIP',
                          'IMAX',
                          'FOUR_DX'
                )
            ),

    CONSTRAINT halls_status_check
        CHECK (
            status IN (
                       'ACTIVE',
                       'INACTIVE',
                       'MAINTENANCE'
                )
            ),

    CONSTRAINT halls_capacity_check
        CHECK (capacity > 0),

    CONSTRAINT fk_halls_cinema
        FOREIGN KEY (cinema_id)
            REFERENCES public.cinemas (id)
);


-- ============================================================
-- 3.4. TẠO BẢNG SEATS
-- ============================================================

CREATE TABLE public.seats
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at   TIMESTAMP(6) WITHOUT TIME ZONE,
    row_name     VARCHAR(10) NOT NULL,
    seat_number  INTEGER NOT NULL,
    status       VARCHAR(30) NOT NULL,
    updated_at   TIMESTAMP(6) WITHOUT TIME ZONE,
    hall_id      BIGINT NOT NULL,
    seat_type_id BIGINT NOT NULL,

    CONSTRAINT seats_pkey
        PRIMARY KEY (id),

    CONSTRAINT uk_seat_hall_row_number
        UNIQUE (hall_id, row_name, seat_number),

    CONSTRAINT seats_status_check
        CHECK (
            status IN (
                       'ACTIVE',
                       'BROKEN',
                       'DISABLED'
                )
            ),

    CONSTRAINT seats_number_check
        CHECK (seat_number > 0),

    CONSTRAINT fk_seats_hall
        FOREIGN KEY (hall_id)
            REFERENCES public.halls (id),

    CONSTRAINT fk_seats_seat_type
        FOREIGN KEY (seat_type_id)
            REFERENCES public.seat_types (id)
);


-- ============================================================
-- 3.5. TẠO BẢNG HALL_MAINTENANCE
-- ============================================================

CREATE TABLE public.hall_maintenance
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    end_time   TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    reason     TEXT,
    start_time TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    status     VARCHAR(30) NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    hall_id    BIGINT NOT NULL,

    CONSTRAINT hall_maintenance_pkey
        PRIMARY KEY (id),

    CONSTRAINT hall_maintenance_status_check
        CHECK (
            status IN (
                       'SCHEDULED',
                       'IN_PROGRESS',
                       'COMPLETED',
                       'CANCELLED'
                )
            ),

    CONSTRAINT hall_maintenance_time_check
        CHECK (end_time > start_time),

    CONSTRAINT fk_hall_maintenance_hall
        FOREIGN KEY (hall_id)
            REFERENCES public.halls (id)
);


